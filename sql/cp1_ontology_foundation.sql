CREATE DATABASE IF NOT EXISTS ONTOLOGY_DEMO_DB;
CREATE SCHEMA IF NOT EXISTS ONTOLOGY_DEMO_DB.CORE;

USE DATABASE ONTOLOGY_DEMO_DB;
USE SCHEMA CORE;

CREATE TABLE IF NOT EXISTS ISSUE_TYPES (
    ISSUE_ID INTEGER,
    ISSUE_NAME VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS ISSUE_RELATIONS (
    PARENT_ISSUE_ID INTEGER,
    CHILD_ISSUE_ID INTEGER
);

CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    ISSUE_ID INTEGER,
    ORDER_AMOUNT NUMBER(10,2)
);

-- Idempotent sample data loading

MERGE INTO ISSUE_TYPES t
USING (
    SELECT column1 AS ISSUE_ID, column2 AS ISSUE_NAME
    FROM VALUES
        (1, 'Order Issue'),
        (2, 'Delivery Issue'),
        (3, 'Payment Issue'),
        (4, 'Weather Delay'),
        (5, 'Carrier Delay')
) s
ON t.ISSUE_ID = s.ISSUE_ID
WHEN MATCHED THEN UPDATE SET t.ISSUE_NAME = s.ISSUE_NAME
WHEN NOT MATCHED THEN INSERT (ISSUE_ID, ISSUE_NAME)
VALUES (s.ISSUE_ID, s.ISSUE_NAME);

MERGE INTO ISSUE_RELATIONS t
USING (
    SELECT column1 AS PARENT_ISSUE_ID,
           column2 AS CHILD_ISSUE_ID
    FROM VALUES
        (1,2),
        (1,3),
        (2,4),
        (2,5)
) s
ON t.PARENT_ISSUE_ID = s.PARENT_ISSUE_ID
AND t.CHILD_ISSUE_ID = s.CHILD_ISSUE_ID
WHEN NOT MATCHED THEN
INSERT (PARENT_ISSUE_ID, CHILD_ISSUE_ID)
VALUES (s.PARENT_ISSUE_ID, s.CHILD_ISSUE_ID);

MERGE INTO ORDERS t
USING (
    SELECT column1 AS ORDER_ID,
           column2 AS CUSTOMER_NAME,
           column3 AS ISSUE_ID,
           column4 AS ORDER_AMOUNT
    FROM VALUES
        (1001, 'Asha', 4, 1250.00),
        (1002, 'Ravi', 5, 890.00),
        (1003, 'Priya', 3, 2100.00)
) s
ON t.ORDER_ID = s.ORDER_ID
WHEN MATCHED THEN UPDATE SET
    t.CUSTOMER_NAME = s.CUSTOMER_NAME,
    t.ISSUE_ID = s.ISSUE_ID,
    t.ORDER_AMOUNT = s.ORDER_AMOUNT
WHEN NOT MATCHED THEN
INSERT (ORDER_ID, CUSTOMER_NAME, ISSUE_ID, ORDER_AMOUNT)
VALUES (s.ORDER_ID, s.CUSTOMER_NAME,
        s.ISSUE_ID, s.ORDER_AMOUNT);

-- Ontology hierarchy validation
-- Starting from Delivery Issue (ID 2),
-- recursively discover its descendants.

WITH RECURSIVE ISSUE_HIERARCHY
    (ISSUE_ID, DEPTH) AS (
    SELECT ISSUE_ID, 0
    FROM ISSUE_TYPES
    WHERE ISSUE_NAME = 'Delivery Issue'

    UNION ALL

    SELECT r.CHILD_ISSUE_ID, h.DEPTH + 1
    FROM ISSUE_RELATIONS r
    JOIN ISSUE_HIERARCHY h
      ON r.PARENT_ISSUE_ID = h.ISSUE_ID
    WHERE h.DEPTH < 10
)
SELECT
    o.ORDER_ID,
    o.CUSTOMER_NAME,
    i.ISSUE_NAME,
    o.ORDER_AMOUNT
FROM ORDERS o
JOIN ISSUE_TYPES i
  ON o.ISSUE_ID = i.ISSUE_ID
JOIN ISSUE_HIERARCHY h
  ON o.ISSUE_ID = h.ISSUE_ID
ORDER BY o.ORDER_ID;
