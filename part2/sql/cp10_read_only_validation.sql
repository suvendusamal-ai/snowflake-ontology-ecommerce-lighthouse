-- CP10.2 Graph integrity
WITH N AS (
 SELECT COUNT(*) NODE_COUNT, COUNT(DISTINCT NODE_ID) UNIQUE_NODE_COUNT
 FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE
), E AS (
 SELECT COUNT(*) EDGE_COUNT, COUNT(DISTINCT EDGE_ID) UNIQUE_EDGE_COUNT,
 COUNT(DISTINCT EDGE_TYPE) EDGE_TYPES
 FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE
), R AS (
 SELECT COUNT_IF(S.NODE_ID IS NULL) MISSING_SOURCE_NODES,
 COUNT_IF(T.NODE_ID IS NULL) MISSING_TARGET_NODES
 FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE G
 LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE S ON G.SOURCE_NODE_ID=S.NODE_ID
 LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE T ON G.TARGET_NODE_ID=T.NODE_ID
)
SELECT *, IFF(N.NODE_COUNT=20 AND N.UNIQUE_NODE_COUNT=20 AND E.EDGE_COUNT=19
 AND E.UNIQUE_EDGE_COUNT=19 AND E.EDGE_TYPES=5 AND R.MISSING_SOURCE_NODES=0
 AND R.MISSING_TARGET_NODES=0,'PASS','FAIL') ACCEPTANCE_RESULT
FROM N CROSS JOIN E CROSS JOIN R;

