-- CP05: Ontology-Grounded Explainable Delivery Investigation
-- Combines recovered KG traversal with validated inactivity policy.
-- Prerequisites: CP01 through CP04.
-- Evaluation timestamp is fixed for reproducible demonstration.
-- This is a read-only investigation query.

WITH PARAMETERS AS (
    SELECT
        TO_TIMESTAMP_NTZ('2026-10-12 12:00:00') AS EVALUATION_TIME,
        48 AS INACTIVITY_THRESHOLD_HOURS
),

GRAPH_CONTEXT AS (
    SELECT
        TRY_TO_NUMBER(o.SOURCE_ID) AS ORDER_ID,
        s.SOURCE_ID AS SHIPMENT_ID,
        sh.SHIPMENT_STATUS,
        i.SOURCE_ID AS ISSUE_ID,
        di.ISSUE_CATEGORY_NAME AS RECORDED_ISSUE,
        p.SOURCE_ID AS PARENT_ISSUE_ID,
        pdi.ISSUE_CATEGORY_NAME AS PARENT_CATEGORY
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE o

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE f
        ON f.SOURCE_NODE_ID = o.NODE_ID
       AND f.EDGE_TYPE = 'FULFILLED_BY'

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE s
        ON s.NODE_ID = f.TARGET_NODE_ID
       AND s.NODE_TYPE = 'SHIPMENT'

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT sh
        ON sh.SHIPMENT_ID = s.SOURCE_ID

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE c
        ON c.SOURCE_NODE_ID = s.NODE_ID
       AND c.EDGE_TYPE = 'CLASSIFIED_AS'

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE i
        ON i.NODE_ID = c.TARGET_NODE_ID
       AND i.NODE_TYPE = 'DELIVERY_ISSUE'

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE di
        ON di.ISSUE_ID = i.SOURCE_ID

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE t
        ON t.SOURCE_NODE_ID = i.NODE_ID
       AND t.EDGE_TYPE = 'SUBCATEGORY_OF'

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE p
        ON p.NODE_ID = t.TARGET_NODE_ID
       AND p.NODE_TYPE = 'DELIVERY_ISSUE'

    LEFT JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE pdi
        ON pdi.ISSUE_ID = p.SOURCE_ID

    WHERE o.NODE_TYPE = 'CUSTOMER_ORDER'
),

EVENT_EVIDENCE AS (
    SELECT
        s.SOURCE_ID AS SHIPMENT_ID,
        ev.EVENT_ID,
        ev.EVENT_TIMESTAMP,
        ev.EVENT_STATUS,
        ev.EVENT_DESCRIPTION
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE s

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE e
        ON e.SOURCE_NODE_ID = s.NODE_ID
       AND e.EDGE_TYPE = 'HAS_EVENT'

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE n
        ON n.NODE_ID = e.TARGET_NODE_ID
       AND n.NODE_TYPE = 'SHIPMENT_EVENT'

    JOIN ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT ev
        ON ev.EVENT_ID = n.SOURCE_ID

    WHERE s.NODE_TYPE = 'SHIPMENT'
),

LATEST_EVENT_TIME AS (
    SELECT
        SHIPMENT_ID,
        MAX(EVENT_TIMESTAMP) AS LAST_EVENT_TIME
    FROM EVENT_EVIDENCE
    GROUP BY SHIPMENT_ID
),

LATEST_EVENT_EVIDENCE AS (
    SELECT
        e.SHIPMENT_ID,
        l.LAST_EVENT_TIME,
        COUNT(*) AS LATEST_EVENT_COUNT,
        MAX(e.EVENT_ID) AS LATEST_EVENT_ID,
        MAX(e.EVENT_STATUS) AS LATEST_EVENT_STATUS,
        MAX(e.EVENT_DESCRIPTION) AS LATEST_EVENT_DESCRIPTION
    FROM EVENT_EVIDENCE e
    JOIN LATEST_EVENT_TIME l
        ON e.SHIPMENT_ID = l.SHIPMENT_ID
       AND e.EVENT_TIMESTAMP = l.LAST_EVENT_TIME
    GROUP BY e.SHIPMENT_ID, l.LAST_EVENT_TIME
)

SELECT
    g.ORDER_ID,
    g.SHIPMENT_ID,
    g.SHIPMENT_STATUS,
    g.RECORDED_ISSUE,
    g.PARENT_CATEGORY,

    CASE WHEN e.LATEST_EVENT_COUNT = 1
         THEN e.LATEST_EVENT_ID END AS LATEST_EVENT_ID,

    CASE WHEN e.LATEST_EVENT_COUNT = 1
         THEN e.LATEST_EVENT_STATUS END AS LATEST_EVENT_STATUS,

    CASE WHEN e.LATEST_EVENT_COUNT = 1
         THEN e.LATEST_EVENT_DESCRIPTION
    END AS LATEST_EVENT_DESCRIPTION,

    e.LAST_EVENT_TIME,
    p.EVALUATION_TIME,

    DATEDIFF(
        'hour',
        e.LAST_EVENT_TIME,
        p.EVALUATION_TIME
    ) AS INACTIVE_HOURS,

    CASE
        WHEN e.LATEST_EVENT_COUNT IS NULL
            THEN 'NO_EVENT_EVIDENCE'

        WHEN e.LATEST_EVENT_COUNT > 1
            THEN 'AMBIGUOUS_LATEST_EVENT'

        WHEN e.LAST_EVENT_TIME > p.EVALUATION_TIME
            THEN 'FUTURE_EVENT'

        WHEN g.SHIPMENT_STATUS = 'DELIVERED'
            THEN 'NOT_ELIGIBLE'

        WHEN g.SHIPMENT_STATUS = 'AT_WAREHOUSE'
         AND g.ISSUE_ID = 'ISS_005'
         AND e.LATEST_EVENT_STATUS = 'AT_WAREHOUSE'
         AND DATEDIFF(
             'second',
             e.LAST_EVENT_TIME,
             p.EVALUATION_TIME
         ) > p.INACTIVITY_THRESHOLD_HOURS * 3600
            THEN 'ELIGIBLE'

        ELSE 'NOT_ELIGIBLE'
    END AS INACTIVITY_DECISION,

    'NOT_ESTABLISHED' AS ROOT_CAUSE_STATUS

FROM GRAPH_CONTEXT g
LEFT JOIN LATEST_EVENT_EVIDENCE e
    ON e.SHIPMENT_ID = g.SHIPMENT_ID
CROSS JOIN PARAMETERS p
ORDER BY g.ORDER_ID;
