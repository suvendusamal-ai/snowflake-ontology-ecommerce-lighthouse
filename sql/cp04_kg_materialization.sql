-- CP04: Knowledge Graph Materialization
-- E-commerce Delivery Ontology Lighthouse
-- Recovered source mappings with idempotent insert-only MERGE.
-- Prerequisites: CP01, CP02, CP03.

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE (
    NODE_ID VARCHAR(255) NOT NULL PRIMARY KEY,
    NODE_TYPE VARCHAR(100) NOT NULL,
    SOURCE_TABLE VARCHAR(255) NOT NULL,
    SOURCE_ID VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE (
    EDGE_ID VARCHAR(255) NOT NULL PRIMARY KEY,
    EDGE_TYPE VARCHAR(100) NOT NULL,
    SOURCE_NODE_ID VARCHAR(255) NOT NULL,
    TARGET_NODE_ID VARCHAR(255) NOT NULL,
    PROVENANCE_SOURCE VARCHAR(255) NOT NULL,
    PROVENANCE_ID VARCHAR(255) NOT NULL
);

-- Materialize entity nodes from five CORE tables.

MERGE INTO ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE t
USING (
    SELECT
        'CUSTOMER:' || CUSTOMER_ID AS NODE_ID,
        'CUSTOMER' AS NODE_TYPE,
        'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER' AS SOURCE_TABLE,
        CUSTOMER_ID AS SOURCE_ID
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER

    UNION ALL

    SELECT
        'CUSTOMER_ORDER:' || TO_VARCHAR(ORDER_ID),
        'CUSTOMER_ORDER',
        'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER',
        TO_VARCHAR(ORDER_ID)
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER

    UNION ALL

    SELECT
        'SHIPMENT:' || SHIPMENT_ID,
        'SHIPMENT',
        'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT',
        SHIPMENT_ID
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT

    UNION ALL

    SELECT
        'SHIPMENT_EVENT:' || EVENT_ID,
        'SHIPMENT_EVENT',
        'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT',
        EVENT_ID
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT

    UNION ALL

    SELECT
        'DELIVERY_ISSUE:' || ISSUE_ID,
        'DELIVERY_ISSUE',
        'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE',
        ISSUE_ID
    FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE
) s
ON t.NODE_ID = s.NODE_ID
WHEN NOT MATCHED THEN
    INSERT (NODE_ID, NODE_TYPE, SOURCE_TABLE, SOURCE_ID)
    VALUES (s.NODE_ID, s.NODE_TYPE, s.SOURCE_TABLE, s.SOURCE_ID);

-- Materialize ontology relationships with deterministic edge IDs.

MERGE INTO ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_EDGE t
USING (
    WITH EDGE_SOURCES AS (
        SELECT
            'PLACED' AS EDGE_TYPE,
            'CUSTOMER:' || CUSTOMER_ID AS SOURCE_NODE_ID,
            'CUSTOMER_ORDER:' || TO_VARCHAR(ORDER_ID) AS TARGET_NODE_ID,
            'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER'
                AS PROVENANCE_SOURCE,
            TO_VARCHAR(ORDER_ID) AS PROVENANCE_ID
        FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER

        UNION ALL

        SELECT
            'FULFILLED_BY',
            'CUSTOMER_ORDER:' || TO_VARCHAR(ORDER_ID),
            'SHIPMENT:' || SHIPMENT_ID,
            'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT',
            SHIPMENT_ID
        FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT

        UNION ALL

        SELECT
            'HAS_EVENT',
            'SHIPMENT:' || SHIPMENT_ID,
            'SHIPMENT_EVENT:' || EVENT_ID,
            'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT',
            EVENT_ID
        FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT

        UNION ALL

        SELECT
            'CLASSIFIED_AS',
            'SHIPMENT:' || SHIPMENT_ID,
            'DELIVERY_ISSUE:' || ISSUE_ID,
            'ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT',
            SHIPMENT_ID
        FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT
        WHERE ISSUE_ID IS NOT NULL

        UNION ALL

        SELECT
            'SUBCATEGORY_OF',
            'DELIVERY_ISSUE:' || CHILD_ISSUE_ID,
            'DELIVERY_ISSUE:' || PARENT_ISSUE_ID,
            'ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.ISSUE_TAXONOMY',
            CHILD_ISSUE_ID
        FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.ISSUE_TAXONOMY
    )
    SELECT
        SHA2(
            TO_VARCHAR(LENGTH(EDGE_TYPE)) || ':' || EDGE_TYPE ||
            TO_VARCHAR(LENGTH(SOURCE_NODE_ID)) || ':' || SOURCE_NODE_ID ||
            TO_VARCHAR(LENGTH(TARGET_NODE_ID)) || ':' || TARGET_NODE_ID,
            256
        ) AS EDGE_ID,
        EDGE_TYPE,
        SOURCE_NODE_ID,
        TARGET_NODE_ID,
        PROVENANCE_SOURCE,
        PROVENANCE_ID
    FROM EDGE_SOURCES
) s
ON t.EDGE_ID = s.EDGE_ID
WHEN NOT MATCHED THEN
    INSERT (
        EDGE_ID, EDGE_TYPE, SOURCE_NODE_ID,
        TARGET_NODE_ID, PROVENANCE_SOURCE, PROVENANCE_ID
    )
    VALUES (
        s.EDGE_ID, s.EDGE_TYPE, s.SOURCE_NODE_ID,
        s.TARGET_NODE_ID, s.PROVENANCE_SOURCE, s.PROVENANCE_ID
    );
