-- CP10.7 Source-to-KG count parity
WITH S AS (
 SELECT 'CUSTOMER' ENTITY_TYPE, COUNT(*) SOURCE_COUNT FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER
 UNION ALL SELECT 'CUSTOMER_ORDER', COUNT(*) FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER
 UNION ALL SELECT 'SHIPMENT', COUNT(*) FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT
 UNION ALL SELECT 'SHIPMENT_EVENT', COUNT(*) FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT
 UNION ALL SELECT 'DELIVERY_ISSUE', COUNT(*) FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE
), G AS (
 SELECT NODE_TYPE ENTITY_TYPE, COUNT(*) GRAPH_COUNT
 FROM ECOM_ONTOLOGY_LIGHTHOUSE_DB.ONTOLOGY.KG_NODE GROUP BY NODE_TYPE
)
SELECT S.ENTITY_TYPE, S.SOURCE_COUNT, COALESCE(G.GRAPH_COUNT,0) GRAPH_COUNT,
 IFF(S.SOURCE_COUNT=COALESCE(G.GRAPH_COUNT,0),'PASS','FAIL') PARITY_RESULT
FROM S LEFT JOIN G ON S.ENTITY_TYPE=G.ENTITY_TYPE ORDER BY S.ENTITY_TYPE;
