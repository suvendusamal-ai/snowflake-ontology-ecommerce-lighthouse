-- CP01: E-commerce Delivery Ontology - CORE Schema
-- Database: ECOM_ONTOLOGY_LIGHTHOUSE_DB
-- Non-destructive setup. Existing tables are not replaced.

CREATE DATABASE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB;
CREATE SCHEMA IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE;

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER (
    CUSTOMER_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER (
    ORDER_ID NUMBER(10,0) NOT NULL PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20) NOT NULL,
    ORDER_DATE DATE NOT NULL,
    ORDER_AMOUNT NUMBER(12,2) NOT NULL,
    FOREIGN KEY (CUSTOMER_ID)
        REFERENCES ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER(CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE (
    ISSUE_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    ISSUE_CATEGORY_NAME VARCHAR(100) NOT NULL,
    ISSUE_DESCRIPTION VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT (
    SHIPMENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    ORDER_ID NUMBER(10,0) NOT NULL UNIQUE,
    ISSUE_ID VARCHAR(20),
    SHIPMENT_STATUS VARCHAR(30) NOT NULL,
    EXPECTED_DELIVERY_DATE DATE NOT NULL,
    FOREIGN KEY (ORDER_ID)
        REFERENCES ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.CUSTOMER_ORDER(ORDER_ID),
    FOREIGN KEY (ISSUE_ID)
        REFERENCES ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.DELIVERY_ISSUE(ISSUE_ID)
);

CREATE TABLE IF NOT EXISTS ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT_EVENT (
    EVENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    SHIPMENT_ID VARCHAR(20) NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP_NTZ(9) NOT NULL,
    EVENT_STATUS VARCHAR(30) NOT NULL,
    EVENT_ISSUE_CODE VARCHAR(50),
    EVENT_DESCRIPTION VARCHAR(500),
    FOREIGN KEY (SHIPMENT_ID)
        REFERENCES ECOM_ONTOLOGY_LIGHTHOUSE_DB.CORE.SHIPMENT(SHIPMENT_ID)
);
